// ─── Resources ───────────────────────────────────────────────────────────────

function mapResources(root: Root, target: ResourceTarget, now: string, fn: (rs: Resource[]) => Resource[]): Root {
  if (target.taskId) {
    return mapTask(root, target.projectId, target.taskId, now, (t) => ({ ...t, resources: fn(t.resources) }));
  }
  return mapProject(root, target.projectId, (p) => ({ ...p, updatedAt: now, resources: fn(p.resources) }));
}

/** Keys in schema order, so an import of an export is identical byte for byte. */
function buildResource(id: string, addedAt: string, input: ResourceInput): Resource {
  const note = clean(input.note);
  return { id, header: input.header.trim(), url: input.url.trim(), ...(note ? { note } : {}), addedAt };
}

export function addResource(root: Root, target: ResourceTarget, id: string, input: ResourceInput, now: string): Root {
  const resource = buildResource(id, now, input);
  return mapResources(root, target, now, (rs) => [...rs, resource]);
}

export function updateResource(
  root: Root,
  target: ResourceTarget,
  resourceId: string,
  input: ResourceInput,
  now: string,
): Root {
  return mapResources(root, target, now, (rs) =>
    rs.map((r) => (r.id === resourceId ? buildResource(r.id, r.addedAt, input) : r)),
  );
}

export function deleteResource(root: Root, target: ResourceTarget, resourceId: string, now: string): Root {
  return mapResources(root, target, now, (rs) => rs.filter((r) => r.id !== resourceId));
}

