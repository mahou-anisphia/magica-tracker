/**
 * Every change to the data, as pure functions: (root, …, now) => new root.
 * Ids are generated by the caller so these stay deterministic and testable.
 * Any change inside a project bumps that project's `updatedAt` (merge uses it);
 * any change to a task bumps the task's `updatedAt` (staleness uses it).
 */

export type ResourceInput = { header: string; url: string; note?: string };
/** Where a resource lives: on a project, or on one of its tasks. */
export type ResourceTarget = { projectId: string; taskId?: string };

const clean = (s: string | undefined) => {
  const t = s?.trim();
  return t ? t : undefined;
};

/** Returns a copy of `obj` with `key` set, or removed when the value is empty. */
function withOptional<T extends object, K extends keyof T>(obj: T, key: K, value: string | undefined): T {
  const copy = { ...obj };
  const v = clean(value);
  if (v === undefined) delete copy[key];
  else (copy as Record<K, unknown>)[key] = v;
  return copy;
}

// ─── Projects ────────────────────────────────────────────────────────────────

export function createProject(root: Root, id: string, name: string, now: string): Root {
  const project: Project = {
    id,
    name: name.trim(),
    archived: false,
    createdAt: now,
    updatedAt: now,
    tasks: [],
    resources: [],
  };
  return { ...root, projects: [...root.projects, project] };
}

function mapProject(root: Root, projectId: string, fn: (p: Project) => Project): Root {
  return {
    ...root,
    projects: root.projects.map((p) => (p.id === projectId ? fn(p) : p)),
  };
}

export function renameProject(root: Root, projectId: string, name: string, now: string): Root {
  const n = name.trim();
  if (!n) return root;
  return mapProject(root, projectId, (p) => ({ ...p, name: n, updatedAt: now }));
}

