export function addBacklogItem(
  root: Root,
  id: string,
  title: string,
  now: string,
  opts: { notes?: string; suggestedProjectId?: string } = {},
): Root {
  const notes = clean(opts.notes);
  const suggestedProjectId = clean(opts.suggestedProjectId);
  const item: BacklogItem = {
    id,
    title: title.trim(),
    ...(notes ? { notes } : {}),
    ...(suggestedProjectId ? { suggestedProjectId } : {}),
    createdAt: now,
    updatedAt: now,
  };
  return { ...root, backlog: [...root.backlog, item] };
}

function mapBacklog(root: Root, itemId: string, now: string, fn: (b: BacklogItem) => BacklogItem): Root {
  return {
    ...root,
    backlog: root.backlog.map((b) => (b.id === itemId ? { ...fn(b), updatedAt: now } : b)),
  };
}

export function renameBacklogItem(root: Root, itemId: string, title: string, now: string): Root {
  const t = title.trim();
  if (!t) return root;
  return mapBacklog(root, itemId, now, (b) => ({ ...b, title: t }));
}

export function setBacklogNotes(root: Root, itemId: string, notes: string, now: string): Root {
  return mapBacklog(root, itemId, now, (b) => withOptional(b, 'notes', notes));
}

export function deleteBacklogItem(root: Root, itemId: string): Root {
  return { ...root, backlog: root.backlog.filter((b) => b.id !== itemId) };
}

/** Backlog item → open task at the end of the project. Notes come along. */
export function promote(root: Root, itemId: string, projectId: string, now: string): Root {
  const item = root.backlog.find((b) => b.id === itemId);
  if (!item || !root.projects.some((p) => p.id === projectId)) return root;
  const task: Task = {
    id: item.id,
    title: item.title,
    done: false,
    status: 'todo',
    ...(item.notes ? { notes: item.notes } : {}),
    createdAt: now,
    updatedAt: now,
    subtasks: [],
    resources: [],
  };
  const next = mapProject(root, projectId, (p) => ({ ...p, updatedAt: now, tasks: [...p.tasks, task] }));
  return deleteBacklogItem(next, itemId);
}

/** Task → backlog. Sub-tasks and resources are dropped (the UI confirms first). */
export function demote(root: Root, projectId: string, taskId: string, now: string): Root {
  const task = root.projects.find((p) => p.id === projectId)?.tasks.find((t) => t.id === taskId);
  if (!task) return root;
  const next = deleteTask(root, projectId, taskId, now);
  return addBacklogItem(next, task.id, task.title, now, { notes: task.notes, suggestedProjectId: projectId });
}

// ─── Domains ─────────────────────────────────────────────────────────────────

/** A new domain at the end of the list. A blank name changes nothing. */
export function createDomain(root: Root, id: string, name: string, now: string): Root {
  const n = name.trim();
  if (!n) return root;
  const domain: Domain = { id, name: n, createdAt: now, updatedAt: now };
  return { ...root, domains: [...(root.domains ?? []), domain] };
}

export function renameDomain(root: Root, domainId: string, name: string, now: string): Root {
  const n = name.trim();
  if (!n || !root.domains?.some((d) => d.id === domainId)) return root;
  return { ...root, domains: root.domains.map((d) => (d.id === domainId ? { ...d, name: n, updatedAt: now } : d)) };
}

/** Removes a domain; its projects stay, ungrouped. */
export function deleteDomain(root: Root, domainId: string, now: string): Root {
  if (!root.domains?.some((d) => d.id === domainId)) return root;
  return {
    ...root,
    domains: root.domains.filter((d) => d.id !== domainId),
    projects: root.projects.map((p) => (p.domainId === domainId ? ungroup(p, now) : p)),
  };
}

function ungroup(p: Project, now: string): Project {
  const { domainId: _, ...rest } = p;
  return { ...rest, updatedAt: now };
}

/**
 * Moves a project, as dragging it does: into a domain (undefined: none) and
 * just before `beforeId`, or with null after the last project already in
 * that domain. The project order is one list; domains show it in groups.
 */
export function moveProject(root: Root, projectId: string, domainId: string | undefined, beforeId: string | null, now: string): Root {
  const domains = new Set((root.domains ?? []).map((d) => d.id));
  if (domainId !== undefined && !domains.has(domainId)) return root;
  const project = root.projects.find((p) => p.id === projectId);
  if (!project || beforeId === projectId) return root;
  const groupOf = (p: Project) => (p.domainId && domains.has(p.domainId) ? p.domainId : undefined);
  const moved = groupOf(project) === domainId ? project : domainId === undefined ? ungroup(project, now) : { ...project, domainId, updatedAt: now };
  const rest = root.projects.filter((p) => p.id !== projectId);
  let at = beforeId ? rest.findIndex((p) => p.id === beforeId) : -1;
  if (at < 0) {
    const last = rest.findLastIndex((p) => groupOf(p) === domainId);
    at = last < 0 ? rest.length : last + 1;
  }
  const projects = [...rest.slice(0, at), moved, ...rest.slice(at)];
  return projects.every((p, i) => p === root.projects[i]) ? root : { ...root, projects };
}

/**
 * Drops one project on another to group them: a new domain holding both,
 * the dropped one just after the other. Name it later; it starts as `name`.
 */
export function groupProjects(root: Root, domainId: string, name: string, targetId: string, droppedId: string, now: string): Root {
  const target = root.projects.find((p) => p.id === targetId);
  if (!target || targetId === droppedId || !root.projects.some((p) => p.id === droppedId)) return root;
  let r = createDomain(root, domainId, name, now);
  r = setProjectDomain(r, targetId, domainId, now);
  const after = r.projects[r.projects.findIndex((p) => p.id === targetId) + 1];
  return moveProject(r, droppedId, domainId, after && after.id !== droppedId ? after.id : null, now);
}

/** Puts a project in a domain, or (undefined) in none. An unknown domain changes nothing. */
export function setProjectDomain(root: Root, projectId: string, domainId: string | undefined, now: string): Root {
  if (domainId !== undefined && !root.domains?.some((d) => d.id === domainId)) return root;
  return mapProject(root, projectId, (p) => {
    if (p.domainId === domainId) return p;
    return domainId === undefined ? ungroup(p, now) : { ...p, domainId, updatedAt: now };
  });
}

// ─── Calendar entries ────────────────────────────────────────────────────────

/** What a calendar entry is made of. `time`, `effort` and `done` only apply to events. */
export type EntryInput = {
  kind: EntryKind;
  title: string;
  date: string;
  until?: string;
  time?: string;
  effort?: number;
  notes?: string;
};

const validEntry = (e: EntryInput) =>
  ENTRY_KINDS.includes(e.kind) &&
  !!e.title.trim() &&
  isCalendarDate(e.date) &&
  (!e.until || isCalendarDate(e.until)) &&
  (e.time === undefined || e.time === '' || /^([01]\d|2[0-3]):[0-5]\d$/.test(e.time)) &&
  (e.effort === undefined || (Number.isFinite(e.effort) && e.effort >= 0 && e.effort <= 100));

/** Keys in schema order, so an import of an export is identical byte for byte. */
function buildEntry(base: Pick<CalendarEntry, 'id' | 'done' | 'doneAt' | 'createdAt'>, input: EntryInput, now: string): CalendarEntry {
  const until = clean(input.until);
  const time = clean(input.time);
  const notes = clean(input.notes);
  return normalizeEntry(
    {
      id: base.id,
      kind: input.kind,
      title: input.title.trim(),
      date: input.date,
      ...(until ? { until } : {}),
      ...(time ? { time } : {}),
      ...(input.effort !== undefined ? { effort: input.effort } : {}),
      done: base.done,
      ...(base.doneAt ? { doneAt: base.doneAt } : {}),
      ...(notes ? { notes } : {}),
      createdAt: base.createdAt,
      updatedAt: now,
    },
    now,
  );
}

/** Adds an event, leave or a holiday. Anything invalid (a blank title, a bad date) changes nothing. */
export function addEntry(root: Root, id: string, input: EntryInput, now: string): Root {
  if (!validEntry(input)) return root;
  const entry = buildEntry({ id, done: false, createdAt: now }, input, now);
  return { ...root, calendar: [...(root.calendar ?? []), entry] };
}

/** Replaces an entry's fields, keeping whether it is done. */
export function updateEntry(root: Root, id: string, input: EntryInput, now: string): Root {
  if (!validEntry(input) || !root.calendar?.some((e) => e.id === id)) return root;
  return { ...root, calendar: root.calendar.map((e) => (e.id === id ? buildEntry(e, input, now) : e)) };
}

/** Ticks an event done, or reopens it. Leave and holidays are never done. */
export function setEntryDone(root: Root, id: string, done: boolean, now: string): Root {
  const entry = root.calendar?.find((e) => e.id === id);
  if (!entry || entry.kind !== 'event' || entry.done === done) return root;
  const { doneAt: _, ...rest } = entry;
  const next: CalendarEntry = done ? { ...rest, done, doneAt: now, updatedAt: now } : { ...rest, done, updatedAt: now };
  return { ...root, calendar: root.calendar!.map((e) => (e.id === id ? next : e)) };
}

export function deleteEntry(root: Root, id: string): Root {
  if (!root.calendar?.some((e) => e.id === id)) return root;
  return { ...root, calendar: root.calendar.filter((e) => e.id !== id) };
}

/**
 * An event → a task at the end of a project, as promoting a backlog item does.
 * Its date becomes the deadline (with `until`, the start and the deadline),
 * and its allocation, notes and done state come along. The task keeps its id.
 */
export function moveEntryToProject(root: Root, id: string, projectId: string, now: string): Root {
  const entry = root.calendar?.find((e) => e.id === id);
  if (!entry || entry.kind !== 'event' || !root.projects.some((p) => p.id === projectId)) return root;
  const task: Task = normalizeTask(
    {
      id: entry.id,
      title: entry.title,
      done: entry.done,
      ...(entry.doneAt ? { doneAt: entry.doneAt } : {}),
      status: entry.done ? 'done' : 'todo',
      due: entry.until ?? entry.date,
      ...(entry.until ? { startsOn: entry.date } : {}),
      ...(entry.effort !== undefined ? { effort: entry.effort } : {}),
      ...(entry.notes ? { notes: entry.notes } : {}),
      createdAt: entry.createdAt,
      updatedAt: now,
      subtasks: [],
      resources: [],
    },
    now,
  );
  const next = mapProject(root, projectId, (p) => ({ ...p, updatedAt: now, tasks: [...p.tasks, task] }));
  return deleteEntry(next, id);
}

// ─── Timesheet ───────────────────────────────────────────────────────────────

/**
 * Whole days given to a project in a month ("2026-10"). Zero removes the
 * month; the project's months stay in order.
 */
export function setTimesheetDays(root: Root, projectId: string, month: string, days: number, now: string): Root {
  if (!isCalendarMonth(month) || !Number.isInteger(days) || days < 0 || days > 31) return root;
  const project = root.projects.find((p) => p.id === projectId);
  const existing = project?.timesheet?.find((t) => t.month === month);
  if (!project || (existing?.days ?? 0) === days) return root;
  // New days are charged to the project's cost center; days already given keep theirs.
  const charge = existing ? existing.costCenterId : root.costCenters?.some((c) => c.id === project.costCenterId) ? project.costCenterId : undefined;
  return mapProject(root, projectId, (p) => {
    const current = p.timesheet ?? [];
    const others = current.filter((t) => t.month !== month);
    const entry: TimesheetMonth = { month, days, ...(charge ? { costCenterId: charge } : {}) };
    const timesheet: TimesheetMonth[] = days ? [...others, entry].sort((a, b) => a.month.localeCompare(b.month)) : others;
    const { timesheet: _, ...rest } = p;
    return timesheet.length ? { ...rest, timesheet, updatedAt: now } : { ...rest, updatedAt: now };
  });
}

/** Gives every project in `to` the days it had in `from`, replacing what `to` held. */
export function copyTimesheetMonth(root: Root, from: string, to: string, now: string): Root {
  if (!isCalendarMonth(from) || !isCalendarMonth(to) || from === to) return root;
  return root.projects.reduce((r, p) => setTimesheetDays(r, p.id, to, p.timesheet?.find((t) => t.month === from)?.days ?? 0, now), root);
}

// ─── Cost centers ────────────────────────────────────────────────────────────

/** A cost center is known by a code, a name, or both; at least one. */
export type CostCenterInput = { code?: string; name?: string };

function buildCostCenter(base: Pick<CostCenter, 'id' | 'createdAt'>, input: CostCenterInput, now: string): CostCenter | null {
  const code = clean(input.code);
  const name = clean(input.name);
  if (!code && !name) return null;
  return { id: base.id, ...(code ? { code } : {}), ...(name ? { name } : {}), createdAt: base.createdAt, updatedAt: now };
}

/** A new cost center at the end of the list. Without a code or a name, nothing changes. */
export function createCostCenter(root: Root, id: string, input: CostCenterInput, now: string): Root {
  const costCenter = buildCostCenter({ id, createdAt: now }, input, now);
  return costCenter ? { ...root, costCenters: [...(root.costCenters ?? []), costCenter] } : root;
}

export function updateCostCenter(root: Root, id: string, input: CostCenterInput, now: string): Root {
  const current = root.costCenters?.find((c) => c.id === id);
  const next = current && buildCostCenter(current, input, now);
  if (!next) return root;
  return { ...root, costCenters: root.costCenters!.map((c) => (c.id === id ? next : c)) };
}

/**
 * Removes a cost center. Its projects are left without one, and days charged
 * to it are charged to none (the UI says how many first).
 */
export function deleteCostCenter(root: Root, id: string, now: string): Root {
  if (!root.costCenters?.some((c) => c.id === id)) return root;
  return {
    ...root,
    costCenters: root.costCenters.filter((c) => c.id !== id),
    projects: root.projects.map((p) => {
      const charged = p.timesheet?.some((t) => t.costCenterId === id);
      if (p.costCenterId !== id && !charged) return p;
      const { costCenterId, ...rest } = p;
      const timesheet = p.timesheet?.map(({ costCenterId: c, ...t }) => (c && c !== id ? { ...t, costCenterId: c } : t));
      return { ...(costCenterId === id ? rest : p), ...(timesheet ? { timesheet } : {}), updatedAt: now };
    }),
  };
}

/**
 * Charges a project to a cost center (undefined: none) from this month on:
 * this month's days and any later ones move with it; earlier months keep the
 * cost center they were charged to. An unknown cost center changes nothing.
 */
export function setProjectCostCenter(root: Root, projectId: string, costCenterId: string | undefined, now: string): Root {
  if (costCenterId !== undefined && !root.costCenters?.some((c) => c.id === costCenterId)) return root;
  const from = localDateStamp(new Date(now)).slice(0, 7);
  return mapProject(root, projectId, (p) => {
    if (p.costCenterId === costCenterId) return p;
    const { costCenterId: _, ...rest } = p;
    const timesheet = p.timesheet?.map(({ costCenterId: c, ...t }) => {
      const charge = t.month >= from ? costCenterId : c;
      return charge ? { ...t, costCenterId: charge } : t;
    });
    return { ...rest, ...(costCenterId ? { costCenterId } : {}), ...(timesheet ? { timesheet } : {}), updatedAt: now };
  });
}

/**
 * Re-charges one month's days to another cost center (undefined: none), as a
 * correction: only that month moves, and the project keeps its own cost
 * center. A month without days, or an unknown cost center, changes nothing.
 */
export function setTimesheetCharge(root: Root, projectId: string, month: string, costCenterId: string | undefined, now: string): Root {
  if (costCenterId !== undefined && !root.costCenters?.some((c) => c.id === costCenterId)) return root;
  const entry = root.projects.find((p) => p.id === projectId)?.timesheet?.find((t) => t.month === month);
  if (!entry || entry.costCenterId === costCenterId) return root;
  return mapProject(root, projectId, (p) => ({
    ...p,
    timesheet: p.timesheet!.map((t) => {
      if (t.month !== month) return t;
      const { costCenterId: _, ...rest } = t;
      return costCenterId ? { ...rest, costCenterId } : rest;
    }),
    updatedAt: now,
  }));
}

// ─── Owner and settings ──────────────────────────────────────────────────────

/** Your name on your exports. The id stays the same across renames; empty removes it. */
export function setOwnerName(root: Root, name: string, makeId: () => string, now: string): Root {
  const n = name.trim();
  const { owner, ...rest } = root;
  if (!n) return { ...rest, updatedAt: now };
  return { ...rest, owner: { id: owner?.id ?? makeId(), name: n }, updatedAt: now };
}

/**
 * When the timesheet starts (null stops keeping one) and which weekdays are
 * worked (1 Monday … 7 Sunday). Days off and capacity follow the weekdays
 * whether or not a timesheet is kept.
 */
export function setWorkdays(root: Root, patch: { from?: string | null; weekdays?: number[] }, now: string): Root {
  if (patch.from && !isCalendarDate(patch.from)) return root;
  if (patch.weekdays && !patch.weekdays.every((d) => Number.isInteger(d) && d >= 1 && d <= 7)) return root;
  const current = workdaySettings(root);
  const from = patch.from === undefined ? current.from : (patch.from ?? undefined);
  const weekdays = patch.weekdays ? [...new Set(patch.weekdays)].sort((a, b) => a - b) : current.weekdays;
  const workdays: WorkdaySettings = { ...(from ? { from } : {}), weekdays };
  return { ...root, settings: { ...root.settings, workdays }, updatedAt: now };
}

export function setAllocationSettings(root: Root, patch: Partial<AllocationSettings>, now: string): Root {
  if (patch.period !== undefined && !ALLOCATION_PERIODS.includes(patch.period)) return root;
  if (patch.unit !== undefined && !ALLOCATION_UNITS.includes(patch.unit)) return root;
  if (patch.maxLoad !== undefined && !(Number.isInteger(patch.maxLoad) && patch.maxLoad >= 100 && patch.maxLoad <= 300)) {
    return root;
  }
  const current = allocationSettings(root);
  return { ...root, settings: { ...root.settings, allocation: { ...current, ...patch } }, updatedAt: now };
}
